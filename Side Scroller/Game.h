#pragma once

#include <SFML/Graphics.hpp>

#include <vector>
#include <string>

#include "Constants.h"
#include "Player.h"
#include "Platform.h"
#include "Enemy.h"
#include "PowerUp.h"
#include "Projectile.h"

// ============================================================
// GAME STATES
// ============================================================

enum class GameState
{
    Playing,
    GameOver,
    LevelComplete
};

// ============================================================
// GAME CLASS
// ============================================================

class Game
{
public:

    Game();

    void run();

private:

    // ========================================================
    // GAME LOOP
    // ========================================================

    void processEvents();

    void update(float deltaTime);

    // ========================================================
    // COLLISIONS
    // ========================================================

    void handleCollisions();

    void handleEnemyCollisions();

    void handlePowerUpCollisions();

    void handleProjectileCollisions();

    void handleGoalCollision();

    // ========================================================
    // CAMERA
    // ========================================================

    void updateCamera();

    // ========================================================
    // RENDERING
    // ========================================================

    void render();

    void renderHUD();

    void renderGameOver();

    void renderLevelComplete();

    // ========================================================
    // PLAYER / LEVEL CONTROL
    // ========================================================

    void resetPlayer();

    void restartGame();

    void startNextLevel();

    // ========================================================
    // SCORE
    // ========================================================

    std::string formatScore() const;

    // ========================================================
    // WINDOW
    // ========================================================

    sf::RenderWindow window;

    // ========================================================
    // PLAYER
    // ========================================================

    Player player;

    // ========================================================
    // WORLD
    // ========================================================

    sf::RectangleShape ground;

    sf::RectangleShape goal;

    // ========================================================
    // CAMERA
    // ========================================================

    sf::View camera;

    // ========================================================
    // PLATFORMS
    // ========================================================

    std::vector<Platform> platforms;

    // ========================================================
    // ENEMIES
    // ========================================================

    std::vector<Enemy> enemies;

    // ========================================================
    // POWER UPS
    // ========================================================

    std::vector<PowerUp> powerUps;

    // ========================================================
    // PROJECTILES
    // ========================================================

    std::vector<Projectile> projectiles;

    // ========================================================
    // FONT
    // ========================================================

    sf::Font font;

    // ========================================================
    // GAME DATA
    // ========================================================

    int lives = 3;

    int score = 0;

    int currentLevel = 1;

    // ========================================================
    // GAME STATE
    // ========================================================

    GameState gameState =
        GameState::Playing;
};